from src.test_cases import *


@用例名称("项目变更新增")
@用例描述(
    """
    项目变更新增
测试步骤:
    1. 进入项目变更页面
    2. 发起预算信息变更并审批
    3. 再次发起预算信息变更并审批
    4. 发起绩效目标变更并审批
"""
)
@用例级别(严重)
def test_项目变更新增(oc_page, oc_page_backup, 项目变更_前置):
    用户名 = "superAdmin"
    项目名称 = 项目变更_前置

    with 测试步骤("切换到项目变更页面"):
        oc_page.项目变更页.set_设置当前用户为(用户名)
        oc_page.项目变更页.navigate()

    with 测试步骤("第一次预算信息变更"):
        变更说明 = {"变更类型": "预算信息变更", "项目名称": 项目名称, "变更说明": "首次调整预算"}
        变更内容 = {"预算金额": "100000"}
        oc_page.项目变更页.新增_按钮.click()
        oc_page.项目变更页.fill_项目变更(变更说明, 项目名称, 变更内容)

        oc_page_backup.我的待办.set_设置当前用户为(用户名)
        oc_page_backup.我的待办.navigate()
        oc_page_backup.我的待办.审批同意("项目变更申请", 用户名)

    with 测试步骤("第二次预算信息变更"):
        变更说明 = {"变更类型": "预算信息变更", "项目名称": 项目名称, "变更说明": "二次调整预算"}
        变更内容 = {"预算金额": "200000"}
        oc_page.项目变更页.新增_按钮.click()
        oc_page.项目变更页.fill_项目变更(变更说明, 变更内容)

        oc_page_backup.我的待办.set_设置当前用户为(用户名)
        oc_page_backup.我的待办.navigate()
        oc_page_backup.我的待办.审批同意("项目变更申请", 用户名)

    with 测试步骤("绩效目标变更"):
        变更说明 = {"变更类型": "绩效目标变更", "项目名称": 项目名称, "变更说明": "调整绩效指标"}
        变更内容 = {"绩效目标": "完成率≥95%"}
        oc_page.项目变更页.新增_按钮.click()
        oc_page.项目变更页.fill_项目变更(变更说明, 变更内容)

        oc_page_backup.我的待办.set_设置当前用户为(用户名)
        oc_page_backup.我的待办.navigate()
        oc_page_backup.我的待办.审批同意("项目变更申请", 用户名)
